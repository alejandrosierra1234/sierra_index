const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const Signage = require('../../js/signage-phase1.js')

const fixedNow = new Date('2030-01-02T03:04:05.000Z')
const admin = { canManage: true, actor: 'Persona sintética' }

const empty = Signage.initialState()
assert.equal(empty.screens.length, 0)
assert.equal(empty.contents.length, 0)
assert.equal(empty.spaces.length, 0)
const room = Signage.createSpace(empty, { name: '  Sala   de coordinación ' }, admin, { now: fixedNow })
assert.equal(room.space.name, 'Sala de coordinación')
assert.equal(room.state.spaces.length, 1)
assert.throws(() => Signage.createSpace(room.state, { name: 'sala de coordinación' }, admin), error => Boolean(error.fields?.name))
const initial = Signage.demoState()
assert.equal(initial.mode, 'local-synthetic-phase3')
assert.equal(initial.screens.length, 2)
assert.equal(initial.contents.length, 2)
assert.ok(initial.screens.every(item => item.evidence === 'Sin telemetría'))
const moved = Signage.updateScreen({ ...initial, spaces: [room.space] }, 'synthetic-screen-a', { name: 'Pantalla norte', spaceId: room.space.id }, admin, { now: fixedNow })
assert.equal(moved.screen.name, 'Pantalla norte')
assert.equal(moved.screen.spaceId, room.space.id)
assert.equal(initial.screens[0].name, 'Pantalla sintética A', 'screen updates do not mutate their input state')

const legacyMemory = new Map([[Signage.STORAGE_KEY, JSON.stringify({ ...initial, testFixtures: undefined })]])
const legacyRepo = Signage.createRepository({ getItem:key=>legacyMemory.get(key)||null, setItem:(key,value)=>legacyMemory.set(key,value), removeItem:key=>legacyMemory.delete(key) })
assert.equal(legacyRepo.load().state.screens.length, 2, 'repository loading alone never deletes local records')
const separatedLegacy = Signage.separateLegacyFixtures(legacyRepo.load().state, { connected: true, now: fixedNow })
assert.equal(separatedLegacy.state.screens.length, 0, 'known demo screens are not mixed into a connected account')
assert.equal(separatedLegacy.state.contents.length, 0, 'known demo content is not mixed into a connected account')
assert.equal(separatedLegacy.archivedCount, 4)
assert.equal(separatedLegacy.ambiguousCount, 0)
assert.equal(separatedLegacy.state.archivedLocalFixtures.screens.length, 2, 'known demo screens remain preserved locally')
assert.equal(separatedLegacy.state.archivedLocalFixtures.contents.length, 2, 'known demo content remains preserved locally')
const untouchedLocalDemo = Signage.separateLegacyFixtures(initial, { connected: false })
assert.equal(untouchedLocalDemo.changed, false, 'offline test mode retains its explicit fixtures')
assert.equal(untouchedLocalDemo.state.screens.length, 2)

const genuineScreen = { id: 'device-real-1', name: 'Pantalla real', kind: 'paired', connectionState: 'connected', history: [] }
const genuineContent = { id: 'content-real-1', type: 'message', title: 'Contenido real', body: 'Conservar', theme: 'neutral' }
const ambiguousLegacy = Signage.normalizeState({ ...Signage.initialState(), screens: [genuineScreen, { id: 'synthetic-screen-a', name: 'Borrador de Alejandro', kind: 'local-test', evidence: 'Editado', history: [] }], contents: [genuineContent, { id: 'synthetic-content-welcome', type: 'message', title: 'Borrador cambiado', body: 'Conservar también', theme: 'teal', createdBy: 'Alejandro' }] })
const separatedAmbiguous = Signage.separateLegacyFixtures(ambiguousLegacy, { connected: true, now: fixedNow })
assert.deepEqual(separatedAmbiguous.state.screens.map(item => item.id), ['device-real-1'], 'genuine devices remain active')
assert.deepEqual(separatedAmbiguous.state.contents.map(item => item.id), ['content-real-1'], 'genuine content remains active')
assert.equal(separatedAmbiguous.ambiguousCount, 2)
const recoveredAmbiguous = Signage.recoverAmbiguousFixtures(separatedAmbiguous.state, { suffix: 'test' })
assert.equal(recoveredAmbiguous.recoveredCount, 2)
assert.ok(recoveredAmbiguous.state.screens.some(item => item.id === 'local-screen-test-1' && item.recoveredFromLegacyFixture), 'ambiguous screen is recovered under a safe local id')
assert.ok(recoveredAmbiguous.state.contents.some(item => item.id === 'local-content-test-1' && item.recoveredFromLegacyFixture), 'ambiguous content is recovered under a safe local id')
assert.ok(recoveredAmbiguous.state.screens.some(item => item.id === 'device-real-1'), 'recovery keeps genuine devices')

const invalid = Signage.validateContent({ title: 'x', body: '', theme: 'unknown' })
assert.equal(invalid.ok, false)
assert.ok(invalid.errors.title)
assert.ok(invalid.errors.body)
assert.equal(invalid.value.theme, 'neutral')

assert.throws(
  () => Signage.createContent(initial, { title: 'Mensaje válido', body: 'Texto válido.' }, { canManage: false }),
  error => error.code === 'SIGNAGE_FORBIDDEN'
)

const created = Signage.createContent(initial, {
  title: '  Mensaje   de prueba  ',
  body: 'Contenido   sintético controlado.',
  theme: 'blue',
}, admin, { now: fixedNow })
assert.equal(created.content.title, 'Mensaje de prueba')
assert.equal(created.content.createdAt, fixedNow.toISOString())
assert.equal(initial.contents.length, 2, 'las operaciones no deben mutar el estado de entrada')
assert.equal(created.state.contents.length, 3)
assert.equal(created.state.audit[0].type, 'content.created')

const published = Signage.publishContent(created.state, 'synthetic-screen-b', created.content.id, admin, { now: fixedNow })
assert.equal(published.screen.publishedContentId, created.content.id)
assert.equal(published.screen.publicationVersion, 1)
assert.equal(published.state.audit[0].type, 'screen.published')
assert.equal(Signage.contentForScreen(published.state, 'synthetic-screen-b').content.id, created.content.id)

const stopped = Signage.stopOutput(published.state, 'synthetic-screen-b', admin, { now: fixedNow })
assert.equal(stopped.screen.outputPaused, true)
assert.equal(stopped.screen.publishedContentId, created.content.id, 'stopping preserves the selected content')
assert.equal(Signage.resolvePlayback(stopped.state, 'synthetic-screen-b').source, 'stopped')
assert.equal(Signage.resolvePlayback(stopped.state, 'synthetic-screen-b').content, null)
assert.equal(stopped.state.screens.find(item => item.id === 'synthetic-screen-a').outputPaused, false, 'stopping one screen does not affect another')
const resumed = Signage.publishContent(stopped.state, 'synthetic-screen-b', created.content.id, admin, { now: fixedNow })
assert.equal(resumed.screen.outputPaused, false, 'an intentional publication resumes output')

const second = Signage.publishContent(published.state, 'synthetic-screen-b', 'synthetic-content-welcome', admin, { now: fixedNow })
assert.equal(second.screen.publicationVersion, 2)
const rolledBack = Signage.rollbackScreen(second.state, 'synthetic-screen-b', admin, { now: fixedNow })
assert.equal(rolledBack.screen.publishedContentId, created.content.id)
assert.equal(rolledBack.screen.publicationVersion, 3)
assert.equal(rolledBack.state.audit[0].type, 'screen.rolled_back')

const memory = new Map()
const storage = {
  getItem: key => memory.has(key) ? memory.get(key) : null,
  setItem: (key, value) => memory.set(key, value),
  removeItem: key => memory.delete(key),
}
const repo = Signage.createRepository(storage)
repo.save(rolledBack.state)
assert.equal(repo.load().state.screens[1].publicationVersion, 3)
storage.setItem(Signage.STORAGE_KEY, '{broken')
const recovered = repo.load()
assert.equal(recovered.recovered, true)
assert.equal(recovered.state.mode, 'local-synthetic-phase3')

