const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const html = fs.readFileSync(path.join(__dirname, '../../index.html'), 'utf8')
const start = html.indexOf('function commsCreateOption(')
const end = html.indexOf('function commsFiltered()', start)
const home = html.slice(start, end)
const resultsStart = html.indexOf('function renderCommunicationsResults(){', end)
const resultsEnd = html.indexOf('function newCommunicationDraft()', resultsStart)
const results = html.slice(resultsStart, resultsEnd)

assert.ok(start > 0 && end > start, 'simplified communications library should be defined')
assert.match(home, /data-comms-create/)
assert.match(home, /commsOpenCreateMenu\(event\)/)
assert.match(home, /Elige el formato que necesitas\./)
assert.match(home, /'Memorándum'/)
assert.match(home, /'Convocatoria'/)
assert.match(home, /'Circular informativa'/)
assert.match(home, /'Aviso'/)
assert.match(home, /'Desde Monday'/)
assert.doesNotMatch(home, />Nuevo memo</)
assert.doesNotMatch(home, />Nueva convocatoria</)
assert.match(home, /aria-controls="comms-filter-panel"/)
assert.match(home, /_commsFiltersOpen\?`<div class="comms-filter-panel"/)
assert.match(home, /function commsActiveFilterCount\(\)/)
assert.doesNotMatch(results, /class="comms-document-icon"/)

console.log('PASS: communications library uses one create menu, progressive filters, and non-repetitive rows')
