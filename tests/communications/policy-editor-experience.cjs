const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const html = fs.readFileSync(path.join(__dirname, '../../index.html'), 'utf8')
const review = fs.readFileSync(path.join(__dirname, '../../js/policy-review.js'), 'utf8')

assert.match(html, /function policyRenderEditorWorkspace\(\)/)
assert.match(html, /renderPolicyEditor=policyRenderEditorWorkspace/)
assert.match(html, /class=\"policy-editor-back\"[^>]*aria-label=\"Volver a políticas\"/)
assert.match(html, /siIcon\('arrow-left',16\)/)
assert.match(html, /siIcon\('columns',16\).*Contraer panel/)
assert.match(html, /\['info','settings','Datos'\]/)
assert.match(html, /\['content','file-edit','Contenido'\]/)
assert.match(html, /\['people','users','Firmantes'\]/)
assert.match(html, /\['comments','message','Comentarios'\]/)
assert.match(html, /data-policy-editor-status/)
assert.match(html, /function policySyncEditorStatus\(\)/)
assert.match(html, /class=\"policy-preview-title-icon\">\$\{siIcon\('eye',16\)\}/)
assert.match(html, /Cambios guardados automáticamente/)
assert.match(html, /\.policy-editor-workspace \.policy-panel-collapse\{width:auto;min-width:132px/)
assert.match(html, /function policySchedulePreview\(delay=320\)/)
assert.match(html, /function policyAutosave\(\)[^{]*\{[^}]*policySchedulePreview\(\)/)
assert.doesNotMatch(html, /function policyAutosave\(\)[^{]*\{[^}]*policyRenderPreview\(\)/)
const decodeAt = review.indexOf("await Promise.all([...next.querySelectorAll('img')]")
const swapAt = review.indexOf('sheet.replaceWith(next)')
assert.ok(decodeAt > -1 && swapAt > decodeAt, 'the visible preview must only swap after replacement logos decode')
assert.match(review, /document\.body\.append\(next\)/)
assert.match(review, /paintedImages\.findIndex\(image=>image\.currentSrc===replacement\.currentSrc\|\|image\.src===replacement\.src\)/)
assert.ok(review.indexOf('replacement.replaceWith(paintedImages.splice') > swapAt, 'painted logo nodes must be reused during the atomic swap')

console.log('PASS: policy editor has intentional navigation and a debounced, flicker-free preview')
