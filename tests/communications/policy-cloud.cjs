const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.join(__dirname, '../..')
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8')
const migration = fs.readFileSync(path.join(root, 'update47.sql'), 'utf8')
const presenceMigration = fs.readFileSync(path.join(root, 'update48.sql'), 'utf8')

assert.match(migration, /create table if not exists public\.policy_documents/)
