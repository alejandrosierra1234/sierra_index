assert.match(migration, /function public\.policy_cloud_list\(\)/)
assert.match(migration, /function public\.policy_cloud_save\(p_snapshot jsonb\)/)
assert.match(migration, /authorize\('communications','read'\)/)
assert.match(migration, /authorize\('communications','write'\)/)
assert.match(migration, /revoke all on public\.policy_documents from public,anon,authenticated/)
assert.match(migration, /index_security_migrations\(version\) values\(47\)/)
assert.match(presenceMigration, /create table if not exists public\.policy_presence/)
assert.match(presenceMigration, /function public\.policy_presence_touch\(p_policy_id text\)/)
assert.match(presenceMigration, /revoke all on public\.policy_presence from public,anon,authenticated/)
assert.match(presenceMigration, /account\.full_name/)
assert.match(presenceMigration, /index_security_migrations\(version\) values\(48\)/)

assert.match(html, /const POLICY_CLOUD_MIGRATION_KEY='sierra_policies_cloud_migrated_v1'/)
