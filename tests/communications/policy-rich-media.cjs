const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const vm = require('node:vm')
const { JSDOM } = require('jsdom')

const html = fs.readFileSync(path.join(__dirname, '../../index.html'), 'utf8')
const localPdf = fs.readFileSync(path.join(__dirname, '../../js/policy-pdf-local.js'), 'utf8')
const assets = fs.readFileSync(path.join(__dirname, '../../js/private-assets.js'), 'utf8')
const review = fs.readFileSync(path.join(__dirname, '../../js/policy-review.js'), 'utf8')
const start = html.indexOf('function policyMediaNumber(')
const end = html.indexOf('function policyResponsibilityHtml(', start)
assert(start >= 0 && end > start)

const dom = new JSDOM('<!doctype html><body></body>', { url: 'https://sierra.test/' })
const storage = 'https://assets.test/storage/v1/object/public/product-images/user/policy/photo.webp'
const context = vm.createContext({
  document: dom.window.document,
  policyUid: () => 'media-safe',
  policyDurableAssetUrl: value => value,
  indexAssets: { path: value => value === storage ? 'user/policy/photo.webp' : null },
})
vm.runInContext(html.slice(start, end), context)

const sanitized = context.policySanitize(`<script>alert(1)</script><table onclick="bad()"><tbody><tr><td colspan="99">Celda <figure data-policy-media-id="x" data-policy-width="999" data-policy-height="12" data-policy-zoom="999" data-policy-position-x="-9" data-policy-position-y="111" data-policy-fit="contain" style="position:fixed"><img src="${storage}" alt="Diagrama" onerror="bad()"></figure></td></tr></tbody></table><img src="https://tracker.test/pixel.png">`)
const box = dom.window.document.createElement('div')
box.innerHTML = sanitized
assert.equal(box.querySelectorAll('script').length, 0)
assert.equal(box.querySelectorAll('table.policy-content-table').length, 1)
assert.equal(box.querySelector('td').colSpan, 8)
assert.equal(box.querySelectorAll('img').length, 1, 'external tracking image is rejected')
const figure = box.querySelector('figure.policy-content-image')
assert.equal(figure.dataset.policyWidth, '100')
assert.equal(figure.dataset.policyHeight, '80')
assert.equal(figure.dataset.policyZoom, '300')
assert.equal(figure.dataset.policyPositionX, '0')
assert.equal(figure.dataset.policyPositionY, '100')
assert.equal(figure.dataset.policyFit, 'contain')
assert.equal(figure.style.getPropertyValue('--policy-media-height'), '80px')
assert.equal(figure.style.getPropertyValue('--policy-media-x'), '0%')
assert.equal(figure.style.getPropertyValue('--policy-media-y'), '100%')
assert.equal(figure.querySelector('img').dataset.policySrc, storage)
assert.equal(figure.querySelector('img').getAttribute('onerror'), null)

const listBox = dom.window.document.createElement('div')
listBox.innerHTML = context.policySanitize('<ol data-policy-list-style="alpha" onclick="bad()"><li>Primero<ol data-policy-list-style="alpha"><li>Detalle</li></ol></li></ol><ol data-policy-list-style="roman"><li>Normal</li></ol>')
assert.equal(listBox.querySelector('ol').dataset.policyListStyle, 'alpha')
assert.equal(listBox.querySelector('ol ol').dataset.policyListStyle, 'alpha')
assert.equal(listBox.querySelectorAll('ol')[2].hasAttribute('data-policy-list-style'), false)
assert.equal(listBox.querySelector('ol').getAttribute('onclick'), null)

const breakBox = dom.window.document.createElement('div')
breakBox.innerHTML = context.policySanitize('<div data-policy-page-break="false" class="wrong" onclick="bad()">Texto inyectado</div>')
const pageBreak = breakBox.querySelector('.policy-page-break')
assert.ok(pageBreak, 'manual page breaks survive rich-text sanitizing')
assert.equal(pageBreak.dataset.policyPageBreak, 'true')
assert.equal(pageBreak.getAttribute('contenteditable'), 'false')
assert.equal(pageBreak.getAttribute('onclick'), null)
assert.equal(pageBreak.textContent, 'Salto de página')

assert.match(html, /title="Agregar imagen"/)
